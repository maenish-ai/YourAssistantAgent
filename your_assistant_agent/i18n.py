@dataclass
class Translator:
    language: str = "en"

    def __post_init__(self):
        if self.language not in STRINGS:
            self.language = "en"

    @property
    def rtl(self) -> bool:
        return self.language == "ar"

    def t(self, key: str, **kwargs) -> str:
        text = STRINGS.get(self.language, STRINGS["en"]).get(key, STRINGS["en"].get(key, key))
        return text.format(**kwargs) if kwargs else text
